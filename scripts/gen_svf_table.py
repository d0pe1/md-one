"""Generate dsp/shared/fm1_svf_table.h.

A Chamberlin state-variable filter tunes with

    f = 2 * sin(pi * fc / fs)

which needs sin(), which the target does not have -- no FPU, no libm. So it is
a table, indexed by MIDI note, because every frequency control on this
instrument reads in notes: filter cutoff, EQ sweep, resonator tuning. One
unit, one knob feel.

STABILITY. The Chamberlin form goes unstable as f approaches 2 (fc -> fs/2),
and is only well behaved below roughly fs/6. The table is clamped at
FMAX_Q15, pinning the top of the range near 7 kHz. That is a limit of the
topology, not a tuning choice: above it the filter does not get brighter, it
rings and then explodes.

Usage:
  python3 scripts/gen_svf_table.py            # writes dsp/shared/fm1_svf_table.h
  python3 scripts/gen_svf_table.py --check    # verify the file matches (CI)
"""
import math
import pathlib
import sys

FS = 44100.0
# ~0.977. The Chamberlin form is stable while f + 1/Q < 2, and 1/Q never
# exceeds 2 here, so f = 1.0 (fs/6, 7350 Hz) is the real ceiling. Sitting just
# under it buys the top octave of the sweep -- a high shelf clamped at 5.9 kHz
# is not an "air" control, which is most of what a high shelf is for.
FMAX_Q15 = 32000
DEST = pathlib.Path(__file__).resolve().parent.parent / "dsp" / "shared" / "fm1_svf_table.h"


def hz(note):
    return 440.0 * (2.0 ** ((note - 69) / 12.0))


def coeff(note):
    f = 2.0 * math.sin(math.pi * hz(note) / FS)
    return min(FMAX_Q15, max(1, int(round(f * 32768.0))))


def render():
    vals = [coeff(n) for n in range(128)]
    clamped = next((n for n in range(128) if vals[n] >= FMAX_Q15), 128)
    shown = min(clamped, 127)

    body = []
    for i in range(0, 128, 8):
        body.append("    " + " ".join(f"{v:5d}," for v in vals[i:i + 8]))

    return f"""/* SPDX-License-Identifier: MIT
 *
 * Generated by scripts/gen_svf_table.py -- do not edit by hand.
 *
 * Chamberlin state-variable filter tuning, Q15, indexed by MIDI note:
 *
 *     f = 2 * sin(pi * fc / fs),   fc = 440 * 2^((note-69)/12),  fs = 44100
 *
 *     note   0 ->  {vals[0]:5d}   ({hz(0):9.2f} Hz)
 *     note  60 ->  {vals[60]:5d}   ({hz(60):9.2f} Hz)
 *     note {shown:3d} ->  {vals[shown]:5d}   ({hz(shown):9.2f} Hz)  <- clamp begins
 *     note 127 ->  {vals[127]:5d}   ({hz(127):9.2f} Hz)  (clamped)
 *
 * The clamp is a property of the topology: a Chamberlin SVF is only well
 * behaved below about fs/6, and above that it rings rather than opening up.
 * Notes above {shown} all tune to the same corner. That is honest behaviour --
 * the alternative is a filter that self-destructs at the end of its range.
 */
#ifndef FM1_SVF_TABLE_H
#define FM1_SVF_TABLE_H

#include <stdint.h>

#define FM1_SVF_F_MAX      {FMAX_Q15}
#define FM1_SVF_NOTE_MAX   {shown}   /* above this, every note is the same corner */

static const uint16_t fm1_svf_f[128] = {{
{chr(10).join(body)}
}};

#endif /* FM1_SVF_TABLE_H */
"""


def main():
    text = render()
    if "--check" in sys.argv:
        current = DEST.read_text() if DEST.exists() else ""
        if current != text:
            print(f"{DEST} is stale -- rerun scripts/gen_svf_table.py", file=sys.stderr)
            return 1
        print(f"{DEST} is up to date")
        return 0
    DEST.write_text(text)
    print(f"wrote {DEST}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
