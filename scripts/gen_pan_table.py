#!/usr/bin/env python3
"""Constant-power pan law as a Q12 gain, one entry per 0..127 knob position.

The engine used a LINEAR pan law: a centred voice got 0.5 in each channel and
a hard-panned one got 1.0, so moving PAN across its range changed how loud the
voice was by 6 dB. Measured on a bare CSAW voice: -9.1 dBFS centred against
-3.7 dBFS hard left. A pan control is not supposed to be a volume control.

Constant power holds perceived level flat across the sweep -- gl^2 + gr^2 is
the same everywhere -- which puts the centre at 0.707 instead of 0.5. That is
3 dB louder than before at the cost of 3 dB of bus headroom, a trade worth
making in both directions here: the instrument measured too quiet with one
voice, and four voices at full level were already reaching the soft clipper.

sqrt is not available on the target, and this is decided once per voice per
block, so it is a table. One table serves both channels: the left gain is the
same curve read backwards, which is only true because the law is symmetric.

    python scripts/gen_pan_table.py > dsp/shared/fm1_pan_table.h
"""
import math

N = 128
TOP = N - 1          # 127, the knob's top position
Q12_ONE = 4096

vals = []
for i in range(N):
    g = Q12_ONE * math.sin((i / TOP) * (math.pi / 2.0))
    vals.append(min(int(round(g)), Q12_ONE))

assert vals[0] == 0 and vals[TOP] == Q12_ONE

print("/* SPDX-License-Identifier: MIT")
print(" *")
print(" * Generated by scripts/gen_pan_table.py -- do not edit by hand.")
print(" * Constant-power pan, Q12 (4096 = unity), indexed by the 0..127 knob.")
print(" *")
print(" *   right = fm1_pan_q12[pan]")
print(" *   left  = fm1_pan_q12[127 - pan]")
print(" *")
print(" * Hard over is exactly unity and the far channel exactly zero, so a")
print(" * fully panned voice neither loses level nor leaks.")
print(" */")
print("#ifndef FM1_PAN_TABLE_H")
print("#define FM1_PAN_TABLE_H")
print()
print("#include <stdint.h>")
print()
print("static const uint16_t fm1_pan_q12[128] = {")
for row in range(0, N, 8):
    print("    " + " ".join("%5d," % v for v in vals[row:row + 8]))
print("};")
print()
print("#endif /* FM1_PAN_TABLE_H */")
