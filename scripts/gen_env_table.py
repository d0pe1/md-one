"""Generate dsp/shared/fm1_env_table.h.

Envelope rates for the per-voice VCA, as one-pole coefficients:

    a = 1 - exp(-1 / (tau * fs))

so that  env += (target - env) * a  approaches the target exponentially.

EXPONENTIAL, NOT LINEAR, which is the whole reason this table exists. A linear
amplitude fade from 1.0 to 0.0 is only -6 dB at its halfway point and -20 dB
at nine tenths: nearly all of the audible fade happens in the last fraction,
so it sounds like the note hangs and then drops off a cliff. An exponential
approach is roughly linear in dB, which is what fading sounds like.

tau sweeps geometrically from 0.4 ms to 7 s. A one-pole is within 1% of its
target after about 4.6 tau, so the top of the range is a ~32 second fade --
the ~30 s that docs/SIGNAL_PATH.md section 3 promises.

exp() is not available on the target: no FPU, no libm.

Usage:
  python3 scripts/gen_env_table.py            # writes the header
  python3 scripts/gen_env_table.py --check    # verify it matches (CI)
"""
import math
import pathlib
import sys

FS = 44100.0
TAU_MIN = 0.0004          # seconds, knob 0   -- effectively instant
TAU_MAX = 7.0             # seconds, knob 127 -- ~32 s to settle
DEST = pathlib.Path(__file__).resolve().parent.parent / "dsp" / "shared" / "fm1_env_table.h"


def tau(knob):
    """Geometric sweep, so the knob feels even across four orders of magnitude."""
    t = knob / 127.0
    return TAU_MIN * ((TAU_MAX / TAU_MIN) ** t)


# Q24, NOT Q15.
#
# At 7 seconds the true coefficient is 3.2e-6, which in Q15 rounds to 1 -- a
# 0.74 s time constant, so the slow end of the knob would deliver a 3.4 s fade
# while every comment claimed 32 s. Q24 leaves 54 counts there, about 2%
# error, and the numbers in the generated header are computed back FROM the
# integer so they cannot drift from what the table actually does.
Q = 24
ONE = 1 << Q


def coeff(knob):
    a = 1.0 - math.exp(-1.0 / (tau(knob) * FS))
    # Clamped into [1, ONE-1]: 0 would be an envelope that never moves, and a
    # knob position that silently freezes the VCA is a bug, not a setting.
    return min(ONE - 1, max(1, int(round(a * ONE))))


def settle(knob):
    """Seconds to come within 1% of the target -- about 4.6 time constants.

    Derived from the QUANTISED coefficient, not from the requested tau, so
    this is what the table delivers rather than what was asked for."""
    a = coeff(knob) / ONE
    return 4.6 / (a * FS)


def settle_ms(knob):
    """The same settle time, in whole milliseconds, for the screen.

    Derived from the SAME quantised coefficient as settle(), so the number on
    the panel is the time the table actually delivers -- not the time the
    generator was asked for, and not a second approximation free to drift from
    the first. Capped at 65535 to fit a uint16; the slowest knob is ~32 s."""
    return min(65535, int(round(settle(knob) * 1000.0)))


def render():
    vals = [coeff(n) for n in range(128)]
    ms = [settle_ms(n) for n in range(128)]

    body = []
    for i in range(0, 128, 6):
        body.append("    " + " ".join(f"{v:8d}," for v in vals[i:i + 6]))

    msbody = []
    for i in range(0, 128, 8):
        msbody.append("    " + " ".join(f"{v:6d}," for v in ms[i:i + 8]))

    return f"""/* SPDX-License-Identifier: MIT
 *
 * Generated by scripts/gen_env_table.py -- do not edit by hand.
 *
 * VCA envelope rates, Q24 one-pole coefficients indexed by a 0..127 knob:
 *
 *     env += (int32_t)(((int64_t)(target - env) * fm1_env_a[knob]) >> 24)
 *
 *     knob   0 -> {vals[0]:8d}   settles in {settle(0):8.4f} s
 *     knob  64 -> {vals[64]:8d}   settles in {settle(64):8.4f} s
 *     knob 127 -> {vals[127]:8d}   settles in {settle(127):8.2f} s
 *
 * Q24 rather than Q15: at the slow end the true coefficient is 3.2e-6, which
 * in Q15 rounds to 1 and would give a 3.4 s fade from a knob documented as
 * 32 s. The settle times above are computed back from these integers, so the
 * header cannot claim a range the table does not deliver.
 *
 * The 64-bit multiply is deliberate and allowed -- the chip has no 64-bit
 * DIVIDE, which is the rule in docs/RULES.md; multiplication is fine.
 *
 * Exponential rather than linear: a linear amplitude fade is only -6 dB at
 * its halfway point, so it sounds like the note hangs and then drops. This is
 * roughly linear in dB, which is what fading sounds like.
 *
 * The sweep is geometric, so the knob feels even across four orders of
 * magnitude instead of spending most of its travel on times nobody wants.
 */
#ifndef FM1_ENV_TABLE_H
#define FM1_ENV_TABLE_H

#include <stdint.h>

static const uint32_t fm1_env_a[128] = {{
{chr(10).join(body)}
}};

/* The same settings as a TIME, in milliseconds, for the screen.
 *
 * A bare 0..127 on an envelope knob says nothing a player can act on -- "is
 * 40 a long decay?" has no answer without turning it and listening. These are
 * computed from the coefficients above rather than alongside them, so the
 * panel cannot promise a time the envelope does not take.
 *
 *     knob   0 -> {ms[0]:5d} ms
 *     knob  64 -> {ms[64]:5d} ms
 *     knob 127 -> {ms[127]:5d} ms
 */
static const uint16_t fm1_env_ms[128] = {{
{chr(10).join(msbody)}
}};

#endif /* FM1_ENV_TABLE_H */
"""


def main():
    text = render()
    if "--check" in sys.argv:
        current = DEST.read_text() if DEST.exists() else ""
        if current != text:
            print(f"{DEST} is stale -- rerun scripts/gen_env_table.py", file=sys.stderr)
            return 1
        print(f"{DEST} is up to date")
        return 0
    DEST.write_text(text)
    print(f"wrote {DEST}")
    print(f"  knob 0 settles in {settle(0) * 1000:.2f} ms, "
          f"knob 127 in {settle(127):.1f} s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
