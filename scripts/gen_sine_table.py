#!/usr/bin/env python3
"""Generate dsp/shared/fm1_sine_table.h.

The target has no FPU, so every table the DSP needs is computed here, on the
host, and emitted as plain integers -- the pattern RULES.md asks for ("compute
constants on your computer and write them into the source as numbers").

This is also the seed of the procedural-wavetable workflow the project is aimed
at: the same generator will later emit harmonic-spectrum tables.

  python scripts/gen_sine_table.py            # writes dsp/shared/fm1_sine_table.h
  python scripts/gen_sine_table.py --check    # verify the file matches (CI)
"""
import argparse
import math
import pathlib
import sys

POINTS = 1024          # power of two: the phase's top 10 bits index it
Q15_MAX = 32767


def table():
    # One guard entry past the end so linear interpolation never wraps the index.
    return [int(round(Q15_MAX * math.sin(2 * math.pi * i / POINTS)))
            for i in range(POINTS + 1)]


def render(vals):
    out = [
        "/* SPDX-License-Identifier: MIT",
        " *",
        f" * Generated by scripts/gen_sine_table.py -- do not edit by hand.",
        f" * {POINTS}-point Q15 sine, plus one guard entry so linear interpolation",
        " * between t[i] and t[i+1] needs no index wrap.",
        " */",
        "#ifndef FM1_SINE_TABLE_H",
        "#define FM1_SINE_TABLE_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define FM1_SINE_POINTS {POINTS}",
        f"#define FM1_SINE_BITS   {POINTS.bit_length() - 1}",
        "",
        f"static const int16_t fm1_sine_table[{POINTS} + 1] = {{",
    ]
    for i in range(0, len(vals), 8):
        out.append("    " + ", ".join(f"{v:6d}" for v in vals[i:i + 8]) + ",")
    out += ["};", "", "#endif /* FM1_SINE_TABLE_H */", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the file is stale")
    args = ap.parse_args()

    dest = pathlib.Path(__file__).resolve().parent.parent / "dsp" / "shared" / "fm1_sine_table.h"
    text = render(table())

    if args.check:
        if not dest.exists() or dest.read_text(encoding="utf-8") != text:
            print(f"STALE: {dest} does not match the generator", file=sys.stderr)
            return 1
        print(f"ok: {dest} is current")
        return 0

    dest.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {dest} ({POINTS} points + guard)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
