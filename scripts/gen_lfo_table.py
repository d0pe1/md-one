#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""Generate dsp/shared/fm1_lfo_table.h.

Phase increments for the LFOs, one per 0..127 knob position.

The LFOs run at BLOCK rate -- 44100/256 = 172.27 Hz -- not sample rate.
Everything they modulate is decided once a block anyway (docs/SIGNAL_PATH.md
section 8), so running them per sample would cost 256 times as much to
produce a value nothing reads.

The range is exponential, 0.01 Hz to 20 Hz. A drone machine wants the slow
end to be genuinely slow -- one cycle in a hundred seconds -- far more than
it wants audio-rate modulation, which is what the FM operators are for. A
linear range would put every useful setting in the first three knob steps.

Usage:
  python3 scripts/gen_lfo_table.py            # writes the header
  python3 scripts/gen_lfo_table.py --check    # verify it matches (CI)
"""
import pathlib
import sys

SR = 44100
BLOCK = 256
BLOCK_RATE = SR / BLOCK          # 172.265625 Hz
LO_HZ = 0.01
HI_HZ = 20.0
N = 128

DEST = pathlib.Path(__file__).resolve().parent.parent / "dsp" / "shared" / "fm1_lfo_table.h"


def build():
    incs = []
    for i in range(N):
        f = LO_HZ * (HI_HZ / LO_HZ) ** (i / (N - 1))
        inc = int(round(f / BLOCK_RATE * (1 << 32)))
        # A rate that rounds to zero is an LFO that never moves. The slowest
        # setting must still arrive somewhere, however long it takes.
        incs.append(max(inc, 1))

    # Report the rates computed BACK from the integers that ship, not from the
    # floats that produced them -- the same discipline the envelope table
    # needed, where a coefficient documented as 32 s delivered 3.4 s.
    slow = incs[0] / (1 << 32) * BLOCK_RATE
    fast = incs[-1] / (1 << 32) * BLOCK_RATE

    lines = [
        "/* SPDX-License-Identifier: MIT",
        " *",
        " * Generated by scripts/gen_lfo_table.py -- do not edit by hand.",
        " *",
        " * Phase increment per BLOCK for each of the 128 LFO rate settings,",
        " * exponential across %.2f .. %.1f Hz at %.3f blocks/second."
        % (LO_HZ, HI_HZ, BLOCK_RATE),
        " *",
        " * Measured back from the integers below: rate 0 is %.5f Hz, a period" % slow,
        " * of %.1f s, and rate 127 is %.3f Hz." % (1.0 / slow, fast),
        " */",
        "#ifndef FM1_LFO_TABLE_H",
        "#define FM1_LFO_TABLE_H",
        "",
        "#include <stdint.h>",
        "",
        "#define FM1_LFO_RATES %d" % N,
        "",
        "static const uint32_t fm1_lfo_inc[FM1_LFO_RATES] = {",
    ]
    for r in range(0, N, 4):
        lines.append(("    " + " ".join("%10du," % v for v in incs[r:r + 4])).rstrip())
    lines += ["};", ""]

    # The same rates as a NUMBER THE PLAYER READS, in MILLIHERTZ. Computed
    # back from the shipped integers like everything else here, so the screen
    # cannot claim a rate the LFO does not run at.
    #
    # Millihertz and not hundredths: this instrument lives at the slow end,
    # and in hundredths the first seven settings all quantise to 0.01 Hz --
    # seven knob positions that sound different and read identically, which is
    # the exact failure the readout exists to fix. 10 .. 20000 fits a uint16.
    mhz = [max(1, int(round(v / (1 << 32) * BLOCK_RATE * 1000.0))) for v in incs]
    lines += [
        "/* The same rates in MILLIHERTZ, for the screen: rate 0 is %d"
        % mhz[0],
        " * (%.3f Hz, a %.0f s cycle) and rate 127 is %d (%.1f Hz)."
        % (mhz[0] / 1000.0, 1.0 / slow, mhz[-1], mhz[-1] / 1000.0),
        " *",
        " * A bare 0..127 is unusable on an instrument whose useful range is a",
        " * ten-second cycle: every setting worth having is crowded into the",
        " * bottom quarter of the knob and they all read the same. */",
        "static const uint16_t fm1_lfo_mhz[FM1_LFO_RATES] = {",
    ]
    for r in range(0, N, 8):
        lines.append(("    " + " ".join("%6du," % v for v in mhz[r:r + 8])).rstrip())
    lines += ["};", "", "#endif /* FM1_LFO_TABLE_H */", ""]

    return "\n".join(lines), slow, fast


def main():
    text, slow, fast = build()
    if "--check" in sys.argv:
        if not DEST.exists() or DEST.read_text(encoding="utf-8") != text:
            print(f"{DEST} is stale -- rerun scripts/gen_lfo_table.py", file=sys.stderr)
            return 1
        print(f"{DEST.name}: up to date")
        return 0
    DEST.write_text(text, encoding="utf-8", newline="\n")
    print("%s: %d rates, %.5f Hz (%.1f s) .. %.3f Hz"
          % (DEST.name, N, slow, 1.0 / slow, fast))
    return 0


if __name__ == "__main__":
    sys.exit(main())
