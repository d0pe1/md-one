#!/usr/bin/env python3
"""Trapezoidal (TPT) state-variable filter tuning: g = tan(pi * fc / fs), Q24.

Why a second filter table exists.

fm1_svf_table.h tunes a CHAMBERLIN SVF, f = 2 sin(pi fc / fs), and its own
header records the problem: "a Chamberlin SVF is only well behaved below
about fs/6, and above that it rings rather than opening up", so every note
above 114 clamps to the same corner. Measured on the host, that is worse than
it sounds -- at RES 0 the 12 dB lowpass tops out at a real 2974 Hz and the
24 dB at 1909 Hz, while the panel reads 12543 Hz. The top twelve steps of the
CUT knob do nothing at all.

The trapezoidal SVF has no such limit. It is the bilinear transform of the
analogue prototype, so its warping is exactly tan(pi fc / fs): the coefficient
grows without bound as fc approaches Nyquist instead of the filter going
unstable. At MIDI note 127 and 44.1 kHz, fc/fs is 0.284 -- well inside the
usable range, so the existing 0..127 knob becomes honest end to end rather
than dying two thirds of the way up.

The algorithm is Andrew Simper's (Cytomic, "Solving the continuous SVF
equations using trapezoidal integration"), published and widely
reimplemented. This is our own implementation of it from the published form;
no code was taken from any GPL firmware, because dsp/ is MIT and stays
GPL-free (docs/LICENSE_REGISTER.md).

Q24 is not a free choice. At Q12 or Q13 the low notes' a3 = g^2 * a1 rounds
to zero and the filter holds a constant for ever -- it stops being a filter
and becomes a latch. The bottom of this table is g = 0.00058, so the squared
term needs every one of those bits.

    python scripts/gen_tpt_table.py > dsp/shared/fm1_tpt_table.h
"""
import math

FS = 44100.0
N = 128                 # MIDI notes 0..127, as the CUT knob reads
Q24 = 1 << 24

# The bilinear transform's warping blows up at Nyquist, so the top is capped
# a little below it. 0.45 fs is where lunar-modulator caps its own sweep, and
# nothing in our range comes close: note 127 is 0.284 fs.
MAX_OF_FS = 0.45


def hz(note):
    return 440.0 * (2.0 ** ((note - 69) / 12.0))


vals = []
for n in range(N + 1):              # one guard entry for interpolation
    f = min(hz(n) / FS, MAX_OF_FS)
    g = math.tan(math.pi * f)
    vals.append(min(int(round(g * Q24)), 0x7FFFFFFF))

print("/* SPDX-License-Identifier: MIT")
print(" *")
print(" * Generated by scripts/gen_tpt_table.py -- do not edit by hand.")
print(" *")
print(" * Trapezoidal SVF tuning, Q24, indexed by MIDI note:")
print(" *")
print(" *     g = tan(pi * fc / fs),  fc = 440 * 2^((note-69)/12),  fs = %g" % FS)
print(" *")
for n in (0, 60, 114, 127):
    print(" *     note %3d -> %10d  (%9.2f Hz)" % (n, vals[n], hz(n)))
print(" *")
print(" * Unlike fm1_svf_table.h there is NO clamp in the usable range: note")
print(" * 127 is %.3f fs, and the trapezoidal form stays well behaved to the" % (hz(127) / FS))
print(" * top of it. The whole knob works.")
print(" *")
print(" * One guard entry past the end, so interpolating between t[i] and")
print(" * t[i+1] needs no bounds test at note 127.")
print(" */")
print("#ifndef FM1_TPT_TABLE_H")
print("#define FM1_TPT_TABLE_H")
print()
print("#include <stdint.h>")
print()
print("static const int32_t fm1_tpt_g24[%d] = {" % (N + 1))
for row in range(0, N + 1, 4):
    print("    " + " ".join("%10d," % v for v in vals[row:row + 4]))
print("};")
print()
print("#endif /* FM1_TPT_TABLE_H */")
